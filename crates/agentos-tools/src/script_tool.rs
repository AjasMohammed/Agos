/// An `AgentTool` implementation that executes a user-provided script file.
///
/// The script receives its JSON payload via the `AGENTOS_INPUT` environment
/// variable and must write a JSON object to stdout as its result.
///
/// Execution is sandboxed with `bwrap` (bubblewrap) — the same isolation used
/// by `shell-exec`. Network access is off by default; set `@network: true` or
/// include `network.outbound:x` in `@permissions` to enable it.
pub struct ScriptTool {
    pub(crate) script_path: PathBuf,
    annotations: ScriptAnnotations,
    parsed_permissions: Vec<(String, PermissionOp)>,
}

impl ScriptTool {
    pub fn new(script_path: PathBuf, annotations: ScriptAnnotations) -> Result<Self, AgentOSError> {
        let parsed_permissions = parse_permission_strings(&annotations.permissions)?;
        Ok(Self {
            script_path,
            annotations,
            parsed_permissions,
        })
    }

    pub fn script_path(&self) -> &Path {
        &self.script_path
    }

    pub fn annotations(&self) -> &ScriptAnnotations {
        &self.annotations
    }
}

#[async_trait]
impl AgentTool for ScriptTool {
    fn name(&self) -> &str {
        &self.annotations.name
    }

    fn required_permissions(&self) -> Vec<(String, PermissionOp)> {
        self.parsed_permissions.clone()
    }

    async fn execute(
        &self,
        payload: serde_json::Value,
        context: ToolExecutionContext,
    ) -> Result<serde_json::Value, AgentOSError> {
        let input_json = payload.to_string();
        let data_dir_str = context.data_dir.to_string_lossy().to_string();
        let script_str = self.script_path.to_string_lossy().to_string();
        let timeout = Duration::from_secs(self.annotations.timeout_secs);
        let tool_name = self.annotations.name.clone();

        // bwrap is required — check once and cache the result.
        if !is_bwrap_available().await {
            return Err(AgentOSError::ToolExecutionFailed {
                tool_name,
                reason: "bwrap (bubblewrap) is not installed. Script tools require sandbox \
                         isolation. Install bwrap to enable script tool execution."
                    .into(),
            });
        }

        let mut cmd = Command::new("bwrap");

        // --unshare-all must come first so all subsequent namespace operations
        // (--proc, --dev, --tmpfs, --bind) act inside the new namespaces.
        cmd.arg("--unshare-all");

        // Re-share network only when explicitly requested by the annotation.
        if self.annotations.allow_network {
            cmd.arg("--share-net");
        }

        // Bind standard system directories read-only.
        // Guard each optional path — on UsrMerge distros /bin, /sbin, /lib
        // may not exist as real directories (symlinked to /usr/*).
        cmd.arg("--ro-bind").arg("/usr").arg("/usr");
        for path in ["/bin", "/sbin", "/lib", "/lib64"] {
            if Path::new(path).exists() {
                cmd.arg("--ro-bind").arg(path).arg(path);
            }
        }

        // Bind the script to a fixed path OUTSIDE data_dir so the subsequent
        // writable data_dir bind cannot shadow or override the read-only script mount.
        // Scripts under data_dir/scripts/ would be made writable if we bound data_dir
        // first and then tried to ro-bind a child path — the parent rw-bind shadows it.
        // Using /agentos-script sidesteps that entirely.
        const SCRIPT_SANDBOX_PATH: &str = "/agentos-script";
        cmd.arg("--ro-bind")
            .arg(&script_str)
            .arg(SCRIPT_SANDBOX_PATH)
            // Bind data dir writable — the only location scripts may write.
            .arg("--bind")
            .arg(&data_dir_str)
            .arg(&data_dir_str)
            // Cover sensitive directories with empty tmpfs mounts.
            // /tmp is writable (in-memory tmpfs — scripts may use it freely).
            .arg("--tmpfs")
            .arg("/root")
            .arg("--tmpfs")
            .arg("/etc")
            .arg("--tmpfs")
            .arg("/var")
            .arg("--tmpfs")
            .arg("/home")
            .arg("--tmpfs")
            .arg("/tmp")
            .arg("--dev")
            .arg("/dev")
            .arg("--proc")
            .arg("/proc");

        // When network access is enabled, restore the files DNS resolution needs.
        // /etc was masked with an empty tmpfs above — overlay just the required files.
        // Without these, any HTTPS/DNS call inside the sandbox fails with opaque errors.
        if self.annotations.allow_network {
            for path in [
                "/etc/resolv.conf",
                "/etc/hosts",
                "/etc/ssl/certs",
                "/etc/ca-certificates",
                "/etc/pki",
            ] {
                if Path::new(path).exists() {
                    cmd.arg("--ro-bind").arg(path).arg(path);
                }
            }
        }

        cmd.arg("--chdir")
            .arg(&data_dir_str)
            .arg("--")
            .arg(SCRIPT_SANDBOX_PATH)
            // Clear all inherited env vars — don't leak host secrets into the sandbox.
            // Then re-add only what the script needs. (W8: removed dead pre-clear env block)
            .env_clear()
            .kill_on_drop(true);

        // Minimal environment: PATH for interpreter resolution + AGENTOS_ context vars.
        cmd.env(
            "PATH",
            "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
        )
        .env("AGENTOS_INPUT", &input_json)
        .env("AGENTOS_TASK_ID", context.task_id.to_string())
        .env("AGENTOS_AGENT_ID", context.agent_id.to_string())
        .env("AGENTOS_DATA_DIR", &data_dir_str);

        let output = tokio::select! {
            result = tokio::time::timeout(timeout, cmd.output()) => {
                result
                    .map_err(|_| AgentOSError::ToolExecutionFailed {
                        tool_name: tool_name.clone(),
                        reason: format!(
                            "Script timed out after {}s",
                            self.annotations.timeout_secs
                        ),
                    })?
                    .map_err(|e| AgentOSError::ToolExecutionFailed {
                        tool_name: tool_name.clone(),
                        reason: format!("Failed to spawn script: {}", e),
                    })?
            }
            _ = context.cancellation_token.cancelled() => {
                return Err(AgentOSError::ToolExecutionFailed {
                    tool_name,
                    reason: "Tool execution cancelled".into(),
                });
            }
        };

        let stderr = String::from_utf8_lossy(&output.stderr);

        // UTF-8 safe truncation: walk back from the byte limit to a char boundary.
        let truncate = |s: &str, max: usize| -> String {
            if s.len() <= max {
                return s.to_string();
            }
            let mut end = max;
            while !s.is_char_boundary(end) {
                end -= 1;
            }
            s[..end].to_string()
        };

        if !output.status.success() {
            let exit_code = output.status.code().unwrap_or(-1);
            let reason = if stderr.is_empty() {
                format!("Script exited with code {}", exit_code)
            } else {
                let preview = truncate(stderr.trim(), 500);
                format!("Script exited with code {}: {}", exit_code, preview)
            };
            return Err(AgentOSError::ToolExecutionFailed { tool_name, reason });
        }

        let stdout = String::from_utf8_lossy(&output.stdout);
        let trimmed = stdout.trim();

        // Log stderr at debug level on success so operators can diagnose scripts
        // that write diagnostics to stderr (the standard convention). (W7 fix)
        let stderr_str = stderr.trim();
        if !stderr_str.is_empty() {
            tracing::debug!(
                tool_name = %tool_name,
                stderr = %stderr_str,
                "Script produced stderr output (exit 0)"
            );
        }

        let mut result = serde_json::from_str::<serde_json::Value>(trimmed).map_err(|e| {
            let preview = truncate(trimmed, 200);
            AgentOSError::ToolExecutionFailed {
                tool_name: tool_name.clone(),
                reason: format!(
                    "Script stdout is not valid JSON: {}. Output was: {:?}",
                    e, preview
                ),
            }
        })?;

        // If stderr is non-empty and result is a JSON object, attach a truncated
        // preview under "_stderr" so agents can see diagnostic output.
        if !stderr_str.is_empty() {
            if let Some(obj) = result.as_object_mut() {
                let preview = truncate(stderr_str, 300);
                obj.insert(
                    "_stderr".to_string(),
                    serde_json::Value::String(preview.to_string()),
                );
            }
        }

        Ok(result)
    }
}

// ---------------------------------------------------------------------------
// ScriptRegistry — tracks path → tool_name for unregistration
// ---------------------------------------------------------------------------

/// Tracks which script path corresponds to which tool name.
/// Used by `ScriptWatcher` to unregister tools when their file is deleted.
#[derive(Default)]
pub struct ScriptRegistry {
    path_to_name: HashMap<PathBuf, String>,
}

impl ScriptRegistry {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn record(&mut self, path: PathBuf, name: String) {
        // Evict any existing path that already maps to the same tool name.
        // This prevents ghost entries when a file is renamed but maps to the
        // same @agentos tool: annotation (same name, different path).
        self.path_to_name.retain(|p, n| p == &path || n != &name);
        self.path_to_name.insert(path, name);
    }

    pub fn remove_path(&mut self, path: &Path) -> Option<String> {
        self.path_to_name.remove(path)
    }

    pub fn name_for(&self, path: &Path) -> Option<&str> {
        self.path_to_name.get(path).map(String::as_str)
    }

    /// Iterate over all registered (path, name) pairs.
    pub fn entries(&self) -> impl Iterator<Item = (&PathBuf, &String)> {
        self.path_to_name.iter()
    }
}

// ---------------------------------------------------------------------------
// Permission string parsing
// ---------------------------------------------------------------------------

/// Parse `"resource:ops"` strings into `(resource, PermissionOp)` pairs.
///
/// Examples:
/// - `"fs.data:r"` → `[("fs.data", Read)]`
/// - `"fs.data:rw"` → `[("fs.data", Read), ("fs.data", Write)]`
/// - `"network.outbound:x"` → `[("network.outbound", Execute)]`
pub fn parse_permission_strings(
    perms: &[String],
) -> Result<Vec<(String, PermissionOp)>, AgentOSError> {
    let mut out = Vec::new();
    for perm in perms {
        let (resource, ops_str) = match perm.split_once(':') {
            Some(pair) => pair,
            None => {
                return Err(AgentOSError::SchemaValidation(format!(
                    "Invalid permission string '{}': expected 'resource:ops'",
                    perm
                )))
            }
        };
        for ch in ops_str.chars() {
            let op = match ch {
                'r' => PermissionOp::Read,
                'w' => PermissionOp::Write,
                'x' => PermissionOp::Execute,
                'q' => PermissionOp::Query,
                'o' => PermissionOp::Observe,
                other => {
                    return Err(AgentOSError::SchemaValidation(format!(
                        "Unknown permission op '{}' in '{}'",
                        other, perm
                    )))
                }
            };
            out.push((resource.to_string(), op));
        }
    }
    Ok(out)
}

