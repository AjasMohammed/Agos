/// Parsed metadata extracted from a script file's annotation header.
#[derive(Debug, Clone)]
pub struct ScriptAnnotations {
    /// Tool name (kebab-case). From `@agentos tool:`.
    pub name: String,
    /// Human + LLM readable description.
    pub description: String,
    /// Semver version string.
    pub version: String,
    /// Raw permission strings e.g. `["fs.data:r", "network.outbound:x"]`.
    pub permissions: Vec<String>,
    /// Risk class string e.g. `"readonly_scoped"`.
    pub risk: String,
    /// Max execution seconds.
    pub timeout_secs: u64,
    /// Capability tags for semantic discoverability.
    pub tags: Vec<String>,
    /// Whether to pass `--share-net` to bwrap.
    pub allow_network: bool,
    /// Full JSON Schema from `@schema:` annotation (generated by Python SDK).
    /// When present, this schema is surfaced to the LLM instead of the
    /// free-text description alone.
    pub schema: Option<serde_json::Value>,
}

// ---------------------------------------------------------------------------
// ScriptParser
// ---------------------------------------------------------------------------

/// Parses annotation headers from script files.
///
/// Annotations are embedded in comment lines near the top of the file.
/// Supported comment prefixes: `#`, `//`, `--`.
/// The prefix is detected from the shebang line or file extension.
///
/// A file without `@agentos tool:` is silently ignored (`Ok(None)`).
pub struct ScriptParser;

impl ScriptParser {
    /// Parse a script file and return its annotations, or `None` if the file
    /// does not carry an `@agentos tool:` annotation.
    pub fn parse(path: &Path) -> Result<Option<ScriptAnnotations>, AgentOSError> {
        let content = match std::fs::read_to_string(path) {
            Ok(c) => c,
            // File deleted between the watcher event and the parse — not an error.
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            // Binary file / non-UTF-8 — silently skip, not a script file.
            Err(e) if e.kind() == std::io::ErrorKind::InvalidData => return Ok(None),
            Err(e) => {
                return Err(AgentOSError::StorageError(format!(
                    "Failed to read script {}: {}",
                    path.display(),
                    e
                )))
            }
        };
        let prefix = Self::detect_comment_prefix(&content, path);
        Self::extract_annotations(&content, prefix)
    }

    fn detect_comment_prefix(content: &str, path: &Path) -> &'static str {
        if let Some(first_line) = content.lines().next() {
            if first_line.starts_with("#!") {
                let lower = first_line.to_lowercase();
                if lower.contains("node") || lower.contains("deno") || lower.contains("ts-node") {
                    return "//";
                }
                if lower.contains("lua") {
                    return "--";
                }
                // bash, sh, python, ruby, perl, php, R → "#"
                return "#";
            }
        }
        match path.extension().and_then(|e| e.to_str()) {
            Some("js") | Some("ts") | Some("mjs") | Some("cjs") => "//",
            Some("lua") => "--",
            _ => "#",
        }
    }

    fn extract_annotations(
        content: &str,
        comment_prefix: &str,
    ) -> Result<Option<ScriptAnnotations>, AgentOSError> {
        let mut name: Option<String> = None;
        let mut description = String::new();
        let mut version = "0.1.0".to_string();
        let mut permissions: Vec<String> = vec!["fs.data:r".to_string()];
        let mut risk = "readonly_scoped".to_string();
        let mut timeout_secs: u64 = 30;
        let mut tags: Vec<String> = Vec::new();
        let mut allow_network = false;
        let mut input_hint: Option<String> = None;
        let mut schema: Option<serde_json::Value> = None;

        // Scan only the first 60 lines to avoid reading large scripts entirely.
        for line in content.lines().take(60) {
            let trimmed = line.trim();
            let rest = match trimmed.strip_prefix(comment_prefix) {
                Some(r) => r.trim(),
                None => continue,
            };
            if !rest.starts_with('@') {
                continue;
            }

            if let Some(v) = rest.strip_prefix("@agentos tool:").map(str::trim) {
                name = Some(v.to_string());
            } else if let Some(v) = rest.strip_prefix("@description:").map(str::trim) {
                description = v.to_string();
            } else if let Some(v) = rest.strip_prefix("@version:").map(str::trim) {
                // Reject control characters (ANSI escapes, newlines) and cap length to
                // prevent terminal injection when `agentos script list` renders the version.
                if v.len() <= 64 && v.chars().all(|c| !c.is_control()) {
                    version = v.to_string();
                } else {
                    tracing::warn!(
                        "@version: contains control chars or exceeds 64 bytes — using default"
                    );
                }
            } else if let Some(v) = rest.strip_prefix("@permissions:").map(str::trim) {
                // Merge declared permissions with the default `fs.data:r` rather than
                // replacing it. Scripts almost always need to read their data_dir, and
                // silently stripping the default causes confusing runtime failures.
                let declared = v
                    .split(',')
                    .map(|s| s.trim().to_string())
                    .filter(|s| !s.is_empty());
                for p in declared {
                    if !permissions.contains(&p) {
                        permissions.push(p);
                    }
                }
            } else if let Some(v) = rest.strip_prefix("@risk:").map(str::trim) {
                risk = v.to_string();
            } else if let Some(v) = rest.strip_prefix("@timeout:").map(str::trim) {
                // max(1): reject zero-second timeouts that would expire immediately.
                timeout_secs = v
                    .parse::<u64>()
                    .unwrap_or(30)
                    .clamp(1, MAX_SCRIPT_TIMEOUT_SECS);
            } else if let Some(v) = rest.strip_prefix("@tags:").map(str::trim) {
                tags = v
                    .split(',')
                    .map(|s| s.trim().to_string())
                    .filter(|s| !s.is_empty())
                    .collect();
            } else if let Some(v) = rest.strip_prefix("@network:").map(str::trim) {
                allow_network = v.eq_ignore_ascii_case("true");
            } else if let Some(v) = rest.strip_prefix("@input:").map(str::trim) {
                input_hint = Some(v.to_string());
            } else if let Some(v) = rest.strip_prefix("@schema:").map(str::trim) {
                // Value is compact JSON (one line) generated by the Python SDK.
                // Only accept JSON objects — scalars/arrays are likely annotation
                // mistakes and must not be forwarded to the LLM as tool schema.
                match serde_json::from_str::<serde_json::Value>(v) {
                    Ok(parsed) if parsed.is_object() => schema = Some(parsed),
                    Ok(_) => {
                        tracing::warn!(
                            "@schema: annotation is not a JSON object — falling back to description-only"
                        );
                    }
                    Err(e) => {
                        tracing::warn!(
                            error = %e,
                            "@schema: annotation contains invalid JSON — falling back to description-only"
                        );
                    }
                }
            }
        }

        let name = match name {
            // Whitespace-only or absent annotation — silently treat as "not a script tool".
            Some(n) if !n.is_empty() => n,
            _ => return Ok(None),
        };

        // Validate: kebab-case, no path separators, no dots
        if name.contains('/')
            || name.contains('\\')
            || name.contains('.')
            || !name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        {
            return Err(AgentOSError::SchemaValidation(format!(
                "Script tool name '{}' must be kebab-case (alphanumeric, hyphens, underscores only)",
                name
            )));
        }

        // Derive allow_network from permissions list if not explicitly set
        let allow_network = allow_network
            || permissions
                .iter()
                .any(|p| p.starts_with("network.outbound"));

        // Append input hint to description so the LLM sees it
        let description = match input_hint {
            Some(ref hint) => format!("{} Input: {}", description, hint),
            None => description,
        };

        Ok(Some(ScriptAnnotations {
            name,
            description,
            version,
            permissions,
            risk,
            timeout_secs,
            tags,
            allow_network,
            schema,
        }))
    }
}

